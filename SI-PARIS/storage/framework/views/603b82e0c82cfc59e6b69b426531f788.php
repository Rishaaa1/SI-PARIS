
<script>
    /* Jam & waktu real-time (WIB) untuk halaman petugas */
    document.addEventListener('DOMContentLoaded', function () {
        var fmt = new Intl.DateTimeFormat('id-ID', {
            timeZone: 'Asia/Jakarta', weekday: 'long', day: '2-digit', month: 'long', year: 'numeric',
            hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23'
        });
        function teks(d) {
            var p = {};
            fmt.formatToParts(d).forEach(function (x) { p[x.type] = x.value; });
            return p.weekday + ', ' + p.day + ' ' + p.month + ' ' + p.year + ' pukul ' + p.hour + ':' + p.minute + ':' + p.second + ' WIB';
        }
        function tick() {
            var now = new Date();
            document.querySelectorAll('[data-jam]').forEach(function (el) { el.textContent = teks(now); });
            document.querySelectorAll('[data-ago]').forEach(function (el) {
                var s = Math.max(0, Math.floor((now - new Date(el.getAttribute('data-ago'))) / 1000));
                el.textContent = s < 60 ? 'baru saja'
                    : s < 3600 ? Math.floor(s / 60) + ' menit yang lalu'
                    : s < 86400 ? Math.floor(s / 3600) + ' jam yang lalu'
                    : Math.floor(s / 86400) + ' hari yang lalu';
            });
        }
        tick();
        setInterval(tick, 1000);
    });
</script>
